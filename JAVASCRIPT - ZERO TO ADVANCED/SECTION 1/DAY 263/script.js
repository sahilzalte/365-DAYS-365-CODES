// Arithmatic Operators
// + - / * % ** 

// +
let a = 10;
let b = 20;
console.log(a + b);

// 'Sahil' + ' dev'
console.log('Sahil' + ' dev');
console.log('Sahil' + 10);
console.log('10' + 10);
console.log(10 + '10');

// -
console.log(10 - '5'); // 5
console.log('10' - 5);
console.log('10' - '5');
console.log('Sahil' - 'dev'); // NaN
console.log('10' - 'dev'); // NaN

// *
console.log(5 * '2'); // 10
console.log('5' * '2'); // 10
console.log('Sahil' * 'dev'); // NaN

// /
console.log(10 / '2'); // 5
console.log('10' / '2'); // 5
console.log('Sahil' / 'dev'); // NaN
console.log(10 / 0); // Infinity
console.log(-10 / 0); // -Infinity
console.log(0 / 0); // NaN

// %
console.log(10 % 3); // 1
console.log(10 % 2); // 0
console.log(5 % 2); // 1
console.log(5 % 0); // NaN 

// **
console.log(2 ** 3); // 8
console.log(3 ** 3); // 27
console.log(4 ** 0.5); // 2